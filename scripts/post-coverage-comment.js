#!/usr/bin/env node

/**
 * Posts a coverage summary comment to a GitHub PR.
 * Reads coverage-summary.json from each tested package and posts comparison.
 * 
 * Usage: node scripts/post-coverage-comment.js
 * 
 * Requires environment variables:
 * - GITHUB_TOKEN: GitHub API token
 * - GITHUB_REPOSITORY: owner/repo format
 * - GITHUB_REF: ref name (e.g., refs/pull/123/merge)
 */

const fs = require('fs');
const path = require('path');
const https = require('https');

const TESTED_PACKAGES = ['utils', 'ui', 'wallets'];
const UNCOVERED_PACKAGES = ['sdk', 'types', 'hooks'];

function parseGitHubRef(ref) {
  // Parse PR number from ref like "refs/pull/123/merge"
  const match = ref.match(/refs\/pull\/(\d+)/);
  return match ? parseInt(match[1], 10) : null;
}

function readCoverageSummary(pkg) {
  const coveragePath = path.join(
    __dirname,
    '..',
    'packages',
    pkg,
    'coverage',
    'coverage-summary.json'
  );

  if (!fs.existsSync(coveragePath)) {
    return null;
  }

  try {
    return JSON.parse(fs.readFileSync(coveragePath, 'utf8'));
  } catch (err) {
    console.error(`Failed to read coverage for ${pkg}:`, err.message);
    return null;
  }
}

function formatMetrics(data) {
  if (!data) return null;
  const total = data.total;
  return {
    lines: total.lines.pct,
    functions: total.functions.pct,
    branches: total.branches.pct,
    statements: total.statements.pct,
  };
}

function buildCommentBody() {
  let body = '## 📊 Coverage Report\n\n';

  body += '### ✅ Tested Packages\n\n';
  body += '| Package | Lines | Functions | Branches | Statements |\n';
  body += '|---------|-------|-----------|----------|------------|\n';

  for (const pkg of TESTED_PACKAGES) {
    const coverage = readCoverageSummary(pkg);
    const metrics = formatMetrics(coverage);

    if (metrics) {
      body += `| @stellar-starter-kit/${pkg} | ${metrics.lines}% | ${metrics.functions}% | ${metrics.branches}% | ${metrics.statements}% |\n`;
    } else {
      body += `| @stellar-starter-kit/${pkg} | N/A | N/A | N/A | N/A |\n`;
    }
  }

  body += '\n### ❌ Not Covered (No Test Suite)\n\n';
  body += 'The following packages have no test suites and are not included in coverage:\n\n';
  for (const pkg of UNCOVERED_PACKAGES) {
    body += `- @stellar-starter-kit/${pkg}\n`;
  }

  body += '\n---\n_Coverage report generated by [vitest](https://vitest.dev/)_';

  return body;
}

function postCommentToGitHub(body) {
  const token = process.env.GITHUB_TOKEN;
  const repo = process.env.GITHUB_REPOSITORY;
  const ref = process.env.GITHUB_REF;

  if (!token || !repo || !ref) {
    console.error('Missing required environment variables');
    console.error('  GITHUB_TOKEN:', !!token);
    console.error('  GITHUB_REPOSITORY:', !!repo);
    console.error('  GITHUB_REF:', !!ref);
    process.exit(1);
  }

  const prNumber = parseGitHubRef(ref);
  if (!prNumber) {
    console.log('Not a pull request; skipping comment');
    process.exit(0);
  }

  const [owner, repoName] = repo.split('/');

  const postData = JSON.stringify({
    body,
  });

  const options = {
    hostname: 'api.github.com',
    port: 443,
    path: `/repos/${owner}/${repoName}/issues/${prNumber}/comments`,
    method: 'POST',
    headers: {
      'Authorization': `token ${token}`,
      'Content-Type': 'application/json',
      'Content-Length': postData.length,
      'User-Agent': 'coverage-reporter',
    },
  };

  return new Promise((resolve, reject) => {
    const req = https.request(options, (res) => {
      let data = '';

      res.on('data', (chunk) => {
        data += chunk;
      });

      res.on('end', () => {
        if (res.statusCode === 201) {
          console.log('✅ Coverage comment posted successfully');
          resolve();
        } else {
          reject(new Error(`HTTP ${res.statusCode}: ${data}`));
        }
      });
    });

    req.on('error', reject);
    req.write(postData);
    req.end();
  });
}

async function main() {
  try {
    const body = buildCommentBody();
    console.log('Generated comment body:\n');
    console.log(body);
    console.log('\n');

    await postCommentToGitHub(body);
  } catch (err) {
    console.error('❌ Error posting coverage comment:', err.message);
    process.exit(1);
  }
}

main();
